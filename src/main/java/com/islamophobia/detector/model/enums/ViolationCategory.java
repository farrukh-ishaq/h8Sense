package com.islamophobia.detector.model.enums;

/**
 * Categories of violations/hate speech against Islam
 */
public enum ViolationCategory {

    /** Direct insults against Islam or Prophet Muhammad (PBUH) */
    DIRECT_INSULT,

    /** Misrepresentation of Islamic teachings */
    MISREPRESENTATION,

    /** Generalization/stereotyping of Muslims */
    STEREOTYPING,

    /** Dehumanization of Muslims */
    DEHUMANIZATION,

    /** Incitement to violence against Muslims */
    INCITEMENT_VIOLENCE,

    /** Discrimination advocacy */
    DISCRIMINATION,

    /** Historical revisionism/denial */
    HISTORICAL_REVISIONISM,

    /** Conspiracy theories about Islam */
    CONSPIRACY_THEORY,

    /** Mockery of Islamic practices */
    MOCKERY_PRACTICES,

    /** Other forms of Islamophobia */
    OTHER
}
